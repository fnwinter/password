# v1: fixed salt, 100k iterations (URLs generated by older versions)
LEGACY_SALT = b'sugar_0419'
LEGACY_ITERATIONS = 100000

# v2: random salt per URL, 600k iterations (OWASP recommendation for PBKDF2-SHA256)
V2_PREFIX = 'v2.'
V2_SALT_LENGTH = 16
V2_ITERATIONS = 600000

def derive_key(master_password, salt, iterations):
    kdf = PBKDF2HMAC(
        algorithm=hashes.SHA256(),
        length=32,
        salt=salt,
        iterations=iterations,
    )
    return base64.urlsafe_b64encode(kdf.derive(master_password.encode('utf-8')))

def generateUrl(data, master_password):
    # Parse the JSON data
    sites_data = json.loads(data)
    
    # Convert data to string for encryption
    data_string = json.dumps(sites_data)
    
    # Generate encryption key from master password with a random salt
    salt = os.urandom(V2_SALT_LENGTH)
    key = derive_key(master_password, salt, V2_ITERATIONS)
    
    # Encrypt the data
    fernet = Fernet(key)
    encrypted_data = fernet.encrypt(data_string.encode('utf-8'))
    
    # Format: v2.<base64(salt + fernet token)>
    encrypted_b64 = V2_PREFIX + base64.urlsafe_b64encode(salt + encrypted_data).decode('utf-8')
    
    host_name = window.location.hostname

    url = f"https://{host_name}/password/password.html#d={encrypted_b64}"
    
    # Update the fullUrlInput with the generated URL
    try:
        if document is not None:
            full_url_input = document.getElementById('fullUrlInput')
            full_url_input.value = url
        else:
            print("document is not found")
    except Exception as e:
        print(f"Error updating fullUrlInput: {str(e)}")
    return encrypted_b64

def decrypt(encrypted_b64, master_password):
    if encrypted_b64.startswith(V2_PREFIX):
        raw = base64.urlsafe_b64decode(encrypted_b64[len(V2_PREFIX):])
        salt = raw[:V2_SALT_LENGTH]
        encrypted_data = raw[V2_SALT_LENGTH:]
        key = derive_key(master_password, salt, V2_ITERATIONS)
    else:
        encrypted_data = base64.urlsafe_b64decode(encrypted_b64)
        key = derive_key(master_password, LEGACY_SALT, LEGACY_ITERATIONS)

    return Fernet(key).decrypt(encrypted_data).decode('utf-8')

def decryptUrlData(encrypted_b64, master_password):
    try:
        decrypted_json = decrypt(encrypted_b64, master_password)
        password_js.handleDecryptedData(decrypted_json)
    except Exception as e:
        password_js.handleDecryptedData("")

